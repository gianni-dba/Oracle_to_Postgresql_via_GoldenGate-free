--postgresql

CREATE SCHEMA IF NOT EXISTS luigi AUTHORIZATION ggadmin;
ALTER ROLE ggadmin SET search_path TO luigi, public;
SET search_path TO luigi;

DROP TABLE IF EXISTS transito CASCADE;
DROP TABLE IF EXISTS gestione CASCADE;
DROP TABLE IF EXISTS magazzino CASCADE;
DROP TABLE IF EXISTS spedizione CASCADE;
DROP TABLE IF EXISTS corriere CASCADE;
DROP TABLE IF EXISTS cliente CASCADE;

--   Creazione delle tabelle (tipi Oracle -> PostgreSQL)
--    VARCHAR2(n) -> VARCHAR(n)
--    NUMBER      -> BIGINT
--    NUMBER(p,s) -> NUMERIC(p,s)
--    DATE        -> TIMESTAMP(0) (mantiene data e ora come in Oracle)
--    SYSDATE     -> CURRENT_TIMESTAMP

CREATE TABLE cliente (
    codice_cliente   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(100) NOT NULL,
    cognome          VARCHAR(100),
    ragione_sociale  VARCHAR(200),
    indirizzo        VARCHAR(200) NOT NULL,
    citta            VARCHAR(50) NOT NULL,
    cap              VARCHAR(10),
    telefono         VARCHAR(20),
    email            VARCHAR(100)
);

CREATE TABLE corriere (
    codice_corriere  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(50) NOT NULL,
    cognome          VARCHAR(50) NOT NULL,
    mezzo_trasporto  VARCHAR(30) NOT NULL,
    attivo           CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT chk_attivo CHECK (attivo IN ('S', 'N')),
    CONSTRAINT chk_mezzo CHECK (mezzo_trasporto IN ('FURGONE', 'CAMION', 'MOTO', 'BICICLETTA', 'AUTO'))
);

CREATE TABLE magazzino (
    codice_magazzino  VARCHAR(10) PRIMARY KEY,
    citta             VARCHAR(50) NOT NULL,
    indirizzo         VARCHAR(200),
    capacita_max_kg   NUMERIC(10,2) NOT NULL
);

CREATE TABLE spedizione (
    codice_spedizione       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_spedizione         TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    data_consegna_prevista  TIMESTAMP(0) NOT NULL,
    data_consegna_effettiva TIMESTAMP(0),
    peso                    NUMERIC(10,2),
    volume                  NUMERIC(10,2),
    valore_dichiarato       NUMERIC(10,2),
    codice_mittente         BIGINT NOT NULL,
    codice_destinatario     BIGINT NOT NULL,
    stato_spedizione        VARCHAR(30) DEFAULT 'CREATA' NOT NULL,
    CONSTRAINT chk_stato_sped CHECK (
        stato_spedizione IN ('CREATA', 'PRESA_IN_CARICO', 'PRONTO_PARTENZA', 'IN_TRANSITO', 'IN_CONSEGNA', 'CONSEGNATA', 'RESPINTA', 'SMARRITA')
    ),
    CONSTRAINT fk_mittente FOREIGN KEY (codice_mittente) REFERENCES cliente(codice_cliente),
    CONSTRAINT fk_destinatario FOREIGN KEY (codice_destinatario) REFERENCES cliente(codice_cliente),
    CONSTRAINT chk_date_consegna CHECK (data_consegna_effettiva IS NULL OR data_consegna_effettiva >= data_spedizione)
);

CREATE TABLE gestione (
    codice_corriere    BIGINT NOT NULL,
    codice_spedizione  BIGINT NOT NULL,
    data_assegnazione  TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ruolo              VARCHAR(30) NOT NULL,
    PRIMARY KEY (codice_corriere, codice_spedizione),
    CONSTRAINT fk_gest_corriere FOREIGN KEY (codice_corriere) REFERENCES corriere(codice_corriere),
    CONSTRAINT fk_gest_spedizione FOREIGN KEY (codice_spedizione) REFERENCES spedizione(codice_spedizione)
);

CREATE TABLE transito (
    codice_spedizione  BIGINT NOT NULL,
    codice_magazzino   VARCHAR(10) NOT NULL,
    data_arrivo        TIMESTAMP(0),
    data_partenza      TIMESTAMP(0),
    stato              VARCHAR(30) NOT NULL,
    PRIMARY KEY (codice_spedizione, codice_magazzino),
    CONSTRAINT fk_trans_spedizione FOREIGN KEY (codice_spedizione) REFERENCES spedizione(codice_spedizione),
    CONSTRAINT fk_trans_magazzino FOREIGN KEY (codice_magazzino) REFERENCES magazzino(codice_magazzino),
    CONSTRAINT chk_stato_transito CHECK (stato IN ('IN_ARRIVO', 'IN_DEPOSITO', 'IN_PARTENZA', 'COMPLETATO')),
    CONSTRAINT chk_date_transito CHECK (
        (data_arrivo IS NOT NULL AND data_partenza IS NOT NULL AND data_partenza >= data_arrivo) OR
        (data_arrivo IS NOT NULL AND data_partenza IS NULL) OR
        (data_arrivo IS NULL AND data_partenza IS NULL)
    )
);

CREATE INDEX idx_sped_mittente ON spedizione(codice_mittente);
CREATE INDEX idx_sped_destinatario ON spedizione(codice_destinatario);
CREATE INDEX idx_gest_sped ON gestione(codice_spedizione);
CREATE INDEX idx_trans_mag ON transito(codice_magazzino);
